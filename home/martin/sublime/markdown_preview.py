"""Open the current markdown file in inlyne, the live-reloading viewer.

inlyne (installed system-wide in modules/nixos/packages.nix) watches the file
it is showing and re-renders on every save, so once the preview window is open
there is nothing more to do: keep editing in Sublime and save.

The command is exposed as "Markdown: Open Preview" in the command palette and
bound to alt+p in markdown files (see the .sublime-commands / .sublime-keymap
entries generated by home/martin/sublime.nix).

The pure helpers (no Sublime dependency) live at module level so they can be
unit-tested outside the plugin host.
"""

import os
import subprocess

try:
    import sublime
    import sublime_plugin
except ImportError:  # running the unit tests outside Sublime
    sublime = None
    sublime_plugin = None

MARKDOWN_EXTENSIONS = (".md", ".markdown", ".mdown", ".mkd", ".mkdn")
PREVIEWER = "inlyne"


def is_markdown_file(path):
    """True if `path` names a saved file with a markdown extension."""
    if not path:
        return False
    return os.path.splitext(path)[1].lower() in MARKDOWN_EXTENSIONS


def preview_command(path):
    """The argv that opens `path` in the previewer (a new list each call)."""
    return [PREVIEWER, path]


if sublime_plugin is not None:

    class OpenMarkdownPreviewCommand(sublime_plugin.TextCommand):
        """Launch the previewer on the file in the active view."""

        def run(self, edit):
            path = self.view.file_name()
            if not path:
                sublime.status_message("Save the file before previewing it")
                return
            try:
                # Detached: Sublime must not wait for the viewer to close.
                subprocess.Popen(preview_command(path), start_new_session=True)
            except OSError as error:
                sublime.error_message(
                    "Could not start %s: %s" % (PREVIEWER, error)
                )

        def is_enabled(self):
            return is_markdown_file(self.view.file_name())

        def is_visible(self):
            return is_markdown_file(self.view.file_name())
